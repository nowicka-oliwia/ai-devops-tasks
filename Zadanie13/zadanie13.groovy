
# Zadanie 13 – Dokumentacja kodu za pomocą JSDoc

## 1. Czym jest JSDoc?

JSDoc to standard dokumentowania kodu JavaScript za pomocą
specjalnych komentarzy umieszczanych nad funkcjami, klasami
i innymi elementami programu.

Dzięki JSDoc można opisać działanie funkcji, jej parametry,
typy danych oraz zwracane wartości.

## 2. Utworzone pliki

- fetch-user.js – oryginalna funkcja bez komentarzy dokumentacyjnych.
- fetch-user-documented.js – funkcja z komentarzami JSDoc.

## 3. Zastosowane znaczniki JSDoc

- @function – określa nazwę dokumentowanej funkcji.
- @param – opisuje parametr funkcji.
- @returns – określa wartość zwracaną przez funkcję.
- @async – informuje, że funkcja wykonuje operacje asynchroniczne.
- @throws – opisuje możliwy błąd.
- @example – przedstawia przykład użycia funkcji.

## 4. Porównanie obu wersji

Wersja oryginalna zawiera wyłącznie kod wykonywalny.
Nie wyjaśnia dokładnie, jakie parametry przyjmuje funkcja
i jakie dane zwraca.

Wersja udokumentowana zawiera komentarze JSDoc,
które wyjaśniają działanie funkcji oraz opisują jej parametry,
wartość zwracaną i przykład użycia.

## 5. Wnioski

JSDoc ułatwia zrozumienie kodu i współpracę między programistami.
Dzięki dokumentacji łatwiej korzystać z istniejących funkcji
bez konieczności analizowania całego ich kodu.

Moim zdaniem dokumentowanie kodu jest ważne szczególnie
w większych projektach, w których pracuje kilka osób.
